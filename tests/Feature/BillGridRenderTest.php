<?php

declare(strict_types=1);

namespace Tests\Feature;

use App\Models\Company;
use App\Models\Customer;
use App\Services\ManuscriptService;
use Barryvdh\DomPDF\Facade\Pdf;
use Database\Factories\CompanyFactory;
use Database\Factories\CustomerFactory;
use Database\Factories\ManuscriptFactory;
use Database\Factories\ZoneFactory;
use Illuminate\Foundation\Testing\DatabaseTransactions;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Validation\ValidationException;
use Tests\Feature\Api\Concerns\InteractsWithTenantRoles;
use Tests\TestCase;

/**
 * Exercises the bulk N-up bill grid mechanism (resources/views/pdf/bills/
 * _grid.blade.php + App\Services\ManuscriptService::billDataForCustomers())
 * directly. The HTTP route that drives it in production —
 * GET /manuscripts/bills, ManuscriptController::downloadBills(), the
 * Manuscripts → Export → "Download Bills (by zone)" item — is covered by
 * tests/Feature/Web/ManuscriptTest.php; this file stays at the grid/service
 * layer. Proves real, multi-customer dompdf renders succeed at density
 * 1/2/3/4 by asserting the generated bytes are a genuine PDF (the "%PDF-"
 * magic header), not just that no exception was thrown.
 */
class BillGridRenderTest extends TestCase
{
    use DatabaseTransactions;
    use InteractsWithTenantRoles;

    protected function setUp(): void
    {
        parent::setUp();

        $this->initializeTenant();
    }

    /**
     * @return Collection<int, Customer>
     */
    private function customersWithManuscripts(int $count): Collection
    {
        $zone = ZoneFactory::new()->create();
        $period = now()->format('Y-m');

        return collect(range(1, $count))->map(function () use ($zone, $period) {
            $customer = CustomerFactory::new()->create(['zone_id' => $zone->id, 'bill' => 2500]);

            ManuscriptFactory::new()
                ->forPeriod($period)
                ->create(['customer_id' => $customer->id, 'bill' => 2500, 'total_bill' => 2500]);

            return $customer;
        });
    }

    private function assertGridRendersRealPdf(int $density, int $customerCount): void
    {
        CompanyFactory::new()->create();

        $customers = $this->customersWithManuscripts($customerCount);

        $bills = app(ManuscriptService::class)->billDataForCustomers($customers, null);

        $this->assertCount($customerCount, $bills, 'billDataForCustomers() should return one entry per customer with a manuscript.');

        $perPage = in_array($density, [1, 2, 3, 4], true) ? $density : 1;

        $pdf = Pdf::loadView('pdf.bills._grid', [
            'bills' => $bills,
            'density' => $density,
            'template' => 'classic',
        ]);

        $pdfBytes = $pdf->output();

        $this->assertNotEmpty($pdfBytes);
        $this->assertStringStartsWith('%PDF-', $pdfBytes, "Grid render at density {$density} did not produce a real PDF.");

        // The N-up sheet geometry (resources/views/pdf/bills/_grid.blade.php)
        // must fit exactly one sheet per physical page: a filling set of
        // bills has to produce precisely ceil(N / perPage) pages, with no
        // phantom blank page from a row overflowing the A4 sheet.
        $expectedPages = (int) ceil($customerCount / $perPage);
        $actualPages = $pdf->getDomPDF()->getCanvas()->get_page_count();

        $this->assertSame(
            $expectedPages,
            $actualPages,
            "Grid at density {$density} with {$customerCount} bills should render {$expectedPages} pages (ceil(N/perPage)), got {$actualPages} — a row is likely overflowing the 297mm A4 sheet."
        );
    }

    public function test_grid_renders_a_real_multi_customer_pdf_at_density_1(): void
    {
        $this->assertGridRendersRealPdf(density: 1, customerCount: 3);
    }

    public function test_grid_renders_a_real_multi_customer_pdf_at_density_2(): void
    {
        $this->assertGridRendersRealPdf(density: 2, customerCount: 5);
    }

    public function test_grid_renders_a_real_multi_customer_pdf_at_density_3(): void
    {
        $this->assertGridRendersRealPdf(density: 3, customerCount: 7);
    }

    public function test_grid_renders_a_real_multi_customer_pdf_at_density_4(): void
    {
        $this->assertGridRendersRealPdf(density: 4, customerCount: 7);
    }

    /**
     * Grid geometry for density 3: a single-column, 3-rows-per-sheet stack.
     * Each cell HUGS the compact bill (~78mm of content, 82mm cell) instead
     * of dividing the sheet into equal thirds, so the bills sit close
     * together (owner: "the spacing between the bills is too wide"). Asserts
     * the generated markup directly rather than the rendered PDF.
     */
    public function test_density_3_tiles_three_rows_in_one_column_per_sheet(): void
    {
        CompanyFactory::new()->create();

        $customers = $this->customersWithManuscripts(7);
        $bills = app(ManuscriptService::class)->billDataForCustomers($customers, null);

        $html = view('pdf.bills._grid', [
            'bills' => $bills,
            'density' => 3,
            'template' => 'classic',
        ])->render();

        // 7 bills at 3-up => 3 sheets (3 + 3 + 1), so 3 <table class="sheet-grid">.
        $this->assertSame(3, substr_count($html, 'class="sheet-grid"'));
        // Full-width (100%) single column, content-hugging 82mm cells. 3 rows
        // x 1 col x 3 sheets => 9 cells (padded cells on the ragged last sheet
        // still emit their <td>).
        $this->assertSame(9, substr_count($html, 'width: 100.0000%; height: 82mm;'));
    }

    /**
     * A density > 1 grid always uses the 'compact' template per cell
     * regardless of the $template argument passed in (Kumba Compact is the
     * one sized for a shared sheet) — pass 'modern' here and confirm the
     * render still succeeds cleanly rather than overflowing/erroring, which
     * is what would happen if a full-A4 template were force-fit into a
     * quarter-page cell.
     */
    public function test_density_four_forces_the_compact_template_regardless_of_selection(): void
    {
        CompanyFactory::new()->create(['bill_template' => 'modern']);

        $customers = $this->customersWithManuscripts(4);
        $bills = app(ManuscriptService::class)->billDataForCustomers($customers, null);

        $pdfBytes = Pdf::loadView('pdf.bills._grid', [
            'bills' => $bills,
            'density' => 4,
            'template' => 'modern',
        ])->output();

        $this->assertStringStartsWith('%PDF-', $pdfBytes);
    }

    /**
     * Ragged final chunk: 5 customers at density 4 leaves a second sheet
     * with only 1 real bill and 3 padded empty cells — proves the grid
     * doesn't error on a non-rectangular final chunk.
     */
    public function test_grid_pads_a_ragged_final_chunk_without_erroring(): void
    {
        CompanyFactory::new()->create();

        $customers = $this->customersWithManuscripts(5);
        $bills = app(ManuscriptService::class)->billDataForCustomers($customers, null);

        $pdfBytes = Pdf::loadView('pdf.bills._grid', [
            'bills' => $bills,
            'density' => 4,
            'template' => 'classic',
        ])->output();

        $this->assertStringStartsWith('%PDF-', $pdfBytes);
    }

    /**
     * The performance-bug regression: Company::logoDataUri() must be
     * resolved exactly ONCE for the whole batch, not once per customer —
     * see ManuscriptService::billDataForCustomers()'s doc comment. Every
     * bill in the batch must carry the SAME logo_data_uri string instance
     * value (not merely equal — literally the one value computed once).
     */
    public function test_logo_data_uri_is_resolved_once_and_shared_across_every_bill_in_the_batch(): void
    {
        Storage::fake('public');

        $company = CompanyFactory::new()->current();
        $company->addMedia(UploadedFile::fake()->image('logo.png', 200, 200))->toMediaCollection('logo');
        Company::forgetCache();

        $customers = $this->customersWithManuscripts(4);
        $bills = app(ManuscriptService::class)->billDataForCustomers($customers, null);

        $logoValues = array_map(fn (array $bill) => $bill['logo_data_uri'], $bills);

        $this->assertNotNull($logoValues[0]);
        $this->assertCount(1, array_unique($logoValues), 'Every bill in the batch should share the same resolved logo data URI.');
    }

    /**
     * N+1 regression: resolving each customer's manuscript must be batched,
     * so the query count stays flat as the batch grows — both for an
     * explicit period and for the latest-manuscript (null period) path.
     */
    public function test_bill_data_for_customers_does_not_query_once_per_customer(): void
    {
        CompanyFactory::new()->create();
        Company::forgetCache();
        Company::cached()?->logoDataUri();

        $service = app(ManuscriptService::class);
        $period = now()->format('Y-m');

        $countQueries = function (Collection $customers, ?string $period) use ($service): int {
            $customers = $customers->map(fn (Customer $customer): Customer => $customer->fresh('zone'));

            DB::flushQueryLog();
            DB::enableQueryLog();
            $bills = $service->billDataForCustomers($customers, $period);
            DB::disableQueryLog();

            $this->assertCount($customers->count(), $bills);

            return count(DB::getQueryLog());
        };

        $small = $this->customersWithManuscripts(2);
        $large = $this->customersWithManuscripts(6);

        $this->assertSame($countQueries($small, $period), $countQueries($large, $period));
        $this->assertSame($countQueries($small, null), $countQueries($large, null));
    }

    public function test_bill_data_for_customers_skips_customers_without_a_manuscript_for_the_period(): void
    {
        CompanyFactory::new()->create();

        $withManuscript = $this->customersWithManuscripts(2);
        $without = CustomerFactory::new()->create(['zone_id' => $withManuscript->first()->zone_id]);

        $bills = app(ManuscriptService::class)->billDataForCustomers(
            $withManuscript->push($without),
            now()->format('Y-m'),
        );

        $this->assertSame(
            $withManuscript->take(2)->pluck('id')->all(),
            array_map(fn (array $bill): int => $bill['customer']->id, $bills),
        );
    }

    public function test_bill_data_for_customers_rejects_a_malformed_period(): void
    {
        $this->expectException(ValidationException::class);

        app(ManuscriptService::class)->billDataForCustomers($this->customersWithManuscripts(1), '2026-13');
    }
}
