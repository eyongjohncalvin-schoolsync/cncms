// Writes resources/css/dark.css — the website's dark mode
// (docs/plans/mobile-manager-app.md, wave 7). Run after changing a rule:
//
//   node resources/css/dark.generate.mjs
//
// The pages carry no `dark:` classes; dark mode is applied centrally while
// <html> has the class `dark`:
//  - slate, the only neutral scale in use, is reversed (50 <-> 950 ...),
//    so every grey text, border and background flips at once;
//  - white cards become the dark surface;
//  - a colour's pale tints (50-200: badge and alert backgrounds, borders,
//    rings) become a dark tint of that colour, and its dark text shades
//    (600-950) become light ones;
//  - coloured fills with white text (500-800) are left as they are — they
//    read on dark too.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const colors = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];

// Tailwind 4's slate (node_modules/tailwindcss/theme.css).
const slate = {
    50: 'oklch(98.4% 0.003 247.858)',
    100: 'oklch(96.8% 0.007 247.896)',
    200: 'oklch(92.9% 0.013 255.508)',
    300: 'oklch(86.9% 0.022 252.894)',
    400: 'oklch(70.4% 0.04 256.788)',
    500: 'oklch(55.4% 0.046 257.417)',
    600: 'oklch(44.6% 0.043 257.281)',
    700: 'oklch(37.2% 0.044 257.287)',
    800: 'oklch(27.9% 0.041 260.031)',
    900: 'oklch(20.8% 0.042 265.755)',
    950: 'oklch(12.9% 0.042 264.695)',
};
const shades = Object.keys(slate);

// How much of the colour goes into a tint, by the light shade it replaces.
const tint = { 50: 14, 100: 20, 200: 30 };
const border = { 100: 30, 200: 40, 300: 55 };
// Dark text shade -> the light shade that replaces it.
const lighter = { 600: 400, 700: 300, 800: 300, 900: 200, 950: 100 };

const escape = (name) => name.replace(/:/g, '\\:').replace(/\//g, '\\/');
// :where() keeps a rule as specific as the utility it replaces, so it wins by
// coming later in the utilities layer while hover: and other variants
// still win over it.
const rule = (cls, body, pseudo = '') => `:where(html.dark) .${escape(cls)}${pseudo} { ${body} }`;
const both = (cls, body) => [rule(cls, body), rule(`hover:${cls}`, body, ':hover')];

const out = [];

out.push(`/* Generated by dark.generate.mjs — edit that, then run: node resources/css/dark.generate.mjs */

html.dark {
    color-scheme: dark;
    --dark-ground: ${slate[950]};
    --dark-surface: ${slate[900]};
${shades.map((shade, index) => `    --color-slate-${shade}: ${slate[shades[shades.length - 1 - index]]};`).join('\n')}
    background-color: var(--dark-ground);
}

/* Text with no colour of its own inherits from here, not the browser's black. */
html.dark body { color: var(--color-slate-900); }

/* \`keep-colors\`: a section designed dark already (the sign-in page's brand
   panel) keeps the original slate scale for everything inside it. */
html.dark .keep-colors {
${shades.map((shade) => `    --color-slate-${shade}: ${slate[shade]};`).join('\n')}
}

/* Charts (recharts): grid, axis labels and the tooltip box. */
html.dark .recharts-cartesian-grid line { stroke: var(--color-slate-200); }
html.dark .recharts-cartesian-axis-tick-value, html.dark .recharts-text { fill: var(--color-slate-600); }
html.dark .recharts-default-tooltip { background-color: var(--dark-surface) !important; border-color: var(--color-slate-200) !important; }

/* The utilities it replaces live in this layer: same layer, coming later. */
@layer utilities {

/* White cards and panels: the dark surface. */
${both('bg-white', 'background-color: var(--dark-surface);').join('\n')}
${[60, 70, 85, 90].map((alpha) => rule(`bg-white/${alpha}`, `background-color: color-mix(in oklab, var(--dark-surface) ${alpha}%, transparent);`)).join('\n')}

/* Dark buttons with white text: after the flip they are light, so their text turns dark. */
${[700, 800, 900, 950].map((shade) => rule(`bg-slate-${shade}.text-white`, 'color: var(--dark-ground);')).join('\n')}

/* The veil behind a dialog stays dark whatever the theme. */
${[40, 50, 60, 70, 80].map((alpha) => rule(`bg-slate-900/${alpha}`, `background-color: color-mix(in oklab, ${slate[900]} ${alpha}%, transparent);`)).join('\n')}
`);

for (const color of colors) {
    out.push(`/* ${color} */`);

    for (const [shade, percent] of Object.entries(tint)) {
        out.push(...both(`bg-${color}-${shade}`, `background-color: color-mix(in oklab, var(--color-${color}-500) ${percent}%, var(--dark-surface));`));
    }

    for (const [shade, percent] of Object.entries(border)) {
        const mixed = `color-mix(in oklab, var(--color-${color}-500) ${percent}%, var(--dark-surface))`;
        out.push(...both(`border-${color}-${shade}`, `border-color: ${mixed};`));
        out.push(rule(`ring-${color}-${shade}`, `--tw-ring-color: ${mixed};`));
    }

    for (const [shade, light] of Object.entries(lighter)) {
        out.push(...both(`text-${color}-${shade}`, `color: var(--color-${color}-${light});`));
    }
}

out.push('}');

const target = join(dirname(fileURLToPath(import.meta.url)), 'dark.css');
writeFileSync(target, `${out.join('\n')}\n`);
console.log(`Wrote ${target}`);
